type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (s: string) => string }

const LangContext = createContext<Ctx>({ lang: 'ru', setLang: () => {}, t: (s) => s })

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>('ru')

  useEffect(() => {
    const saved = window.localStorage.getItem('camp-race-lang')
    if (saved === 'kk' || saved === 'ru') setLangState(saved)
  }, [])

  useEffect(() => {
    document.documentElement.lang = lang
  }, [lang])

  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    window.localStorage.setItem('camp-race-lang', l)
  }, [])

  const t = useCallback((s: string) => (lang === 'kk' ? DICT[s] ?? s : s), [lang])

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t])

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>
}

export function useT(): Ctx {
  return useContext(LangContext)
}

export function LangToggle({ compact = false }: { compact?: boolean }) {
  const { lang, setLang } = useT()
  return (
    <div
      className={`inline-flex shrink-0 items-center rounded-full border border-[#d9cde8] bg-white/90 p-0.5 text-[11px] font-bold ${compact ? '' : 'text-xs'}`}
      aria-label="Language"
    >
      {(['kk', 'ru'] as Lang[]).map((code) => (
        <button
          key={code}
          type="button"
          onClick={() => setLang(code)}
          aria-pressed={lang === code}
          className={`rounded-full px-2.5 py-1 transition ${lang === code ? 'bg-[#4c008e] text-white shadow-sm' : 'text-[#4c008e]/70 hover:text-[#4c008e]'}`}
        >
          {code === 'kk' ? 'KZ' : 'RU'}
        </button>
      ))}
    </div>
  )
}